-- Every tenant receives the same protected business-role templates. Existing
-- ADMIN rows remain valid for backwards compatibility, but new assignments are
-- deliberately restricted to MANAGER or STAFF.
INSERT INTO public.roles (tenant_id, name, description, is_system_role)
SELECT tenant.id, role_template.name, role_template.description, TRUE
FROM public.tenants AS tenant
CROSS JOIN (
  VALUES
    ('MANAGER', 'Business manager with daily operations access'),
    ('STAFF', 'Staff member with operational access')
) AS role_template(name, description)
WHERE NOT EXISTS (
  SELECT 1
  FROM public.roles existing_role
  WHERE existing_role.tenant_id = tenant.id
    AND UPPER(existing_role.name) = role_template.name
);

