RETURNS INTEGER
LANGUAGE SQL
IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE LOWER(COALESCE(p_plan, 'starter'))
    WHEN 'pro' THEN 4
    WHEN 'enterprise' THEN 10
    ELSE 0
  END;
$$;

