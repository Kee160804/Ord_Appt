-- Replace the broad membership write policy with fixed business roles. Reads
-- remain membership-scoped; writes are further narrowed by restrictive rules,
-- so older permissive policies cannot grant Staff access to owner controls.
DO $$
DECLARE
  v_table TEXT;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'business_settings', 'business_modules', 'business_hours', 'categories',
    'products', 'services', 'staff', 'staff_services'
  ] LOOP
    IF TO_REGCLASS(FORMAT('public.%I', v_table)) IS NOT NULL
       AND EXISTS (
         SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = v_table AND column_name = 'tenant_id'
       ) THEN
      EXECUTE FORMAT('DROP POLICY IF EXISTS team_admin_insert_required ON public.%I', v_table);
      EXECUTE FORMAT('DROP POLICY IF EXISTS team_admin_update_required ON public.%I', v_table);
      EXECUTE FORMAT('DROP POLICY IF EXISTS team_admin_delete_required ON public.%I', v_table);
      EXECUTE FORMAT(
        'CREATE POLICY team_admin_insert_required ON public.%I AS RESTRICTIVE FOR INSERT TO authenticated
         WITH CHECK (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN''))', v_table);
      EXECUTE FORMAT(
        'CREATE POLICY team_admin_update_required ON public.%I AS RESTRICTIVE FOR UPDATE TO authenticated
         USING (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN''))
         WITH CHECK (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN''))', v_table);
      EXECUTE FORMAT(
        'CREATE POLICY team_admin_delete_required ON public.%I AS RESTRICTIVE FOR DELETE TO authenticated
         USING (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN''))', v_table);
    END IF;
  END LOOP;

  FOREACH v_table IN ARRAY ARRAY[
    'customers', 'orders', 'order_items', 'appointments', 'appointment_services'
  ] LOOP
    IF TO_REGCLASS(FORMAT('public.%I', v_table)) IS NOT NULL
       AND EXISTS (
         SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = v_table AND column_name = 'tenant_id'
       ) THEN
      EXECUTE FORMAT('DROP POLICY IF EXISTS team_operations_insert_required ON public.%I', v_table);
      EXECUTE FORMAT('DROP POLICY IF EXISTS team_operations_update_required ON public.%I', v_table);
      EXECUTE FORMAT('DROP POLICY IF EXISTS team_operations_delete_required ON public.%I', v_table);
      EXECUTE FORMAT(
        'CREATE POLICY team_operations_insert_required ON public.%I AS RESTRICTIVE FOR INSERT TO authenticated
         WITH CHECK (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN'', ''STAFF''))', v_table);
      EXECUTE FORMAT(
        'CREATE POLICY team_operations_update_required ON public.%I AS RESTRICTIVE FOR UPDATE TO authenticated
         USING (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN'', ''STAFF''))
         WITH CHECK (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN'', ''STAFF''))', v_table);
      EXECUTE FORMAT(
        'CREATE POLICY team_operations_delete_required ON public.%I AS RESTRICTIVE FOR DELETE TO authenticated
         USING (public.is_super_admin() OR public.current_tenant_role(tenant_id) IN (''OWNER'', ''MANAGER'', ''ADMIN''))', v_table);
    END IF;
  END LOOP;
END;
$$;

