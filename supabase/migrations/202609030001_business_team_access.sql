CREATE OR REPLACE FUNCTION public.request_tenant_paid_staff_seats(
  p_tenant_id UUID,
  p_requested_paid_seats INTEGER
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_plan TEXT;
  v_max_paid INTEGER;
  v_current_paid INTEGER;
  v_request_id UUID;
BEGIN
  IF NOT public.current_user_owns_tenant(p_tenant_id) THEN
    RAISE EXCEPTION 'Only the business owner can request additional seats.' USING ERRCODE = '42501';
  END IF;
  SELECT LOWER(COALESCE(plan, 'starter')) INTO v_plan FROM public.tenants WHERE id = p_tenant_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Business not found.' USING ERRCODE = 'P0002'; END IF;
  IF NOT public.tenant_subscription_allows_access(p_tenant_id) THEN
    RAISE EXCEPTION 'This business subscription is inactive.' USING ERRCODE = '42501';
  END IF;
  v_max_paid := public.team_plan_max_staff(v_plan) - public.team_plan_included_staff(v_plan);
  IF p_requested_paid_seats < 1 OR p_requested_paid_seats > v_max_paid THEN
    RAISE EXCEPTION 'Choose a paid-seat total allowed by this plan.' USING ERRCODE = '22023';
  END IF;
  SELECT COALESCE(paid_staff_seats, 0) INTO v_current_paid
  FROM public.tenant_seat_entitlements WHERE tenant_id = p_tenant_id;
  IF p_requested_paid_seats <= COALESCE(v_current_paid, 0) THEN
    RAISE EXCEPTION 'Request a paid-seat total above the currently approved amount.' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.tenant_seat_change_requests (tenant_id, requested_paid_seats, requested_by)
  VALUES (p_tenant_id, p_requested_paid_seats, auth.uid())
  ON CONFLICT (tenant_id) WHERE status = 'PENDING' DO UPDATE
  SET requested_paid_seats = EXCLUDED.requested_paid_seats,
      requested_by = EXCLUDED.requested_by,
      created_at = NOW()
  RETURNING id INTO v_request_id;

  INSERT INTO public.team_access_events (tenant_id, actor_id, action, details)
  VALUES (
    p_tenant_id, auth.uid(), 'PAID_STAFF_SEATS_REQUESTED',
    JSONB_BUILD_OBJECT('requestedPaidSeats', p_requested_paid_seats, 'monthlyCharge', p_requested_paid_seats * 2)
  );
  RETURN v_request_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_tenant_seat_admin_summary(p_tenant_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_result JSONB;
BEGIN
  IF NOT public.is_super_admin() THEN
    RAISE EXCEPTION 'Only a platform administrator can review paid seats.' USING ERRCODE = '42501';
  END IF;
  SELECT JSONB_BUILD_OBJECT(
    'paidStaffSeats', COALESCE(entitlement.paid_staff_seats, 0),
    'includedStaff', public.team_plan_included_staff(tenant.plan),
    'maxStaff', public.team_plan_max_staff(tenant.plan),
    'additionalSeatPrice', 2,
    'activeStaff', (
      SELECT COUNT(*)::INTEGER FROM public.tenant_memberships membership
      JOIN public.roles role ON role.id = membership.role_id
      WHERE membership.tenant_id = tenant.id AND membership.is_active = TRUE
        AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF')
    ),
    'pendingRequest', (
      SELECT JSONB_BUILD_OBJECT(
        'id', request.id,
        'requestedPaidSeats', request.requested_paid_seats,
        'createdAt', request.created_at
      )
      FROM public.tenant_seat_change_requests request
      WHERE request.tenant_id = tenant.id AND request.status = 'PENDING'
      ORDER BY request.created_at DESC LIMIT 1
    )
  ) INTO v_result
  FROM public.tenants tenant
  LEFT JOIN public.tenant_seat_entitlements entitlement ON entitlement.tenant_id = tenant.id
  WHERE tenant.id = p_tenant_id;
  IF v_result IS NULL THEN RAISE EXCEPTION 'Business not found.' USING ERRCODE = 'P0002'; END IF;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_tenant_paid_staff_seats(
  p_tenant_id UUID,
  p_paid_staff_seats INTEGER,
  p_request_id UUID DEFAULT NULL,
  p_review_note TEXT DEFAULT ''
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_plan TEXT;
  v_max_paid INTEGER;
  v_included INTEGER;
  v_active INTEGER;
  v_current_paid INTEGER;
BEGIN
  IF NOT public.is_super_admin() THEN
    RAISE EXCEPTION 'Only a platform administrator can approve paid seats.' USING ERRCODE = '42501';
  END IF;
  SELECT LOWER(COALESCE(plan, 'starter')) INTO v_plan FROM public.tenants WHERE id = p_tenant_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Business not found.' USING ERRCODE = 'P0002'; END IF;
  v_included := public.team_plan_included_staff(v_plan);
  v_max_paid := public.team_plan_max_staff(v_plan) - v_included;
  IF p_paid_staff_seats < 0 OR p_paid_staff_seats > v_max_paid THEN
    RAISE EXCEPTION 'Paid staff seats exceed this plan allowance.' USING ERRCODE = '22023';
  END IF;
  SELECT COALESCE(paid_staff_seats, 0) INTO v_current_paid
  FROM public.tenant_seat_entitlements WHERE tenant_id = p_tenant_id;
  IF p_paid_staff_seats > COALESCE(v_current_paid, 0)
     AND NULLIF(BTRIM(COALESCE(p_review_note, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Enter the confirmed payment reference before adding paid seats.' USING ERRCODE = '22023';
  END IF;

  SELECT COUNT(*)::INTEGER INTO v_active
  FROM public.tenant_memberships membership
  JOIN public.roles role ON role.id = membership.role_id
  WHERE membership.tenant_id = p_tenant_id AND membership.is_active = TRUE
    AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF');
  IF v_active > v_included + p_paid_staff_seats THEN
    RAISE EXCEPTION 'Deactivate staff before reducing the authorized seat total.' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.tenant_seat_entitlements (tenant_id, paid_staff_seats, updated_by, updated_at)
  VALUES (p_tenant_id, p_paid_staff_seats, auth.uid(), NOW())
  ON CONFLICT (tenant_id) DO UPDATE
  SET paid_staff_seats = EXCLUDED.paid_staff_seats,
      updated_by = EXCLUDED.updated_by,
      updated_at = NOW();

  IF p_request_id IS NOT NULL THEN
    UPDATE public.tenant_seat_change_requests
    SET status = 'APPROVED', reviewed_by = auth.uid(), reviewed_at = NOW(), review_note = NULLIF(BTRIM(p_review_note), '')
    WHERE id = p_request_id
      AND tenant_id = p_tenant_id
      AND status = 'PENDING'
      AND requested_paid_seats = p_paid_staff_seats;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'The pending seat request no longer matches this approval.' USING ERRCODE = 'P0002';
    END IF;
  END IF;

  INSERT INTO public.team_access_events (tenant_id, actor_id, action, details)
  VALUES (
    p_tenant_id, auth.uid(), 'PAID_STAFF_SEATS_SET',
    JSONB_BUILD_OBJECT('paidStaffSeats', p_paid_staff_seats, 'monthlyCharge', p_paid_staff_seats * 2, 'note', p_review_note)
  );
END;
$$;

