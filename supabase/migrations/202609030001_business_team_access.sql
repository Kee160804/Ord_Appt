  WHERE id = p_membership_id AND tenant_id = p_tenant_id;

  INSERT INTO public.team_access_events (tenant_id, actor_id, action, subject_profile_id, details)
  VALUES (p_tenant_id, auth.uid(), 'TEAM_ROLE_CHANGED', v_subject, JSONB_BUILD_OBJECT('role', v_role));
