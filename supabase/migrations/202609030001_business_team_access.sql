CREATE OR REPLACE FUNCTION public.update_team_member_role(
  p_tenant_id UUID,
  p_membership_id UUID,
  p_role_name TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_role TEXT := UPPER(BTRIM(COALESCE(p_role_name, '')));
  v_role_id UUID;
  v_subject UUID;
BEGIN
  IF NOT public.current_user_owns_tenant(p_tenant_id) THEN
    RAISE EXCEPTION 'Only the business owner can change team roles.' USING ERRCODE = '42501';
