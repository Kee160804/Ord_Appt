CREATE OR REPLACE FUNCTION public.enforce_tenant_staff_seat_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_role TEXT;
  v_capacity INTEGER;
  v_active_staff INTEGER;
BEGIN
  IF NEW.is_active IS NOT TRUE THEN RETURN NEW; END IF;

  SELECT UPPER(role.name) INTO v_role
  FROM public.roles role
  WHERE role.id = NEW.role_id AND role.tenant_id = NEW.tenant_id;

  IF v_role NOT IN ('ADMIN', 'MANAGER', 'STAFF') THEN RETURN NEW; END IF;

  PERFORM PG_ADVISORY_XACT_LOCK(HASHTEXT('team-seats:' || NEW.tenant_id::TEXT));
  v_capacity := COALESCE(public.tenant_authorized_staff_capacity(NEW.tenant_id), 0);

  SELECT COUNT(*)::INTEGER INTO v_active_staff
  FROM public.tenant_memberships membership
  JOIN public.roles role ON role.id = membership.role_id
  WHERE membership.tenant_id = NEW.tenant_id
    AND membership.is_active = TRUE
    AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF')
    AND (TG_OP = 'INSERT' OR membership.id <> NEW.id);

  IF v_active_staff >= v_capacity THEN
    RAISE EXCEPTION 'This business has reached its authorized staff limit. Add a paid seat or change plans first.'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.enforce_tenant_staff_seat_limit() FROM PUBLIC;
DROP TRIGGER IF EXISTS trg_tenant_memberships_staff_seat_limit ON public.tenant_memberships;
CREATE TRIGGER trg_tenant_memberships_staff_seat_limit
BEFORE INSERT OR UPDATE OF role_id, is_active ON public.tenant_memberships
FOR EACH ROW EXECUTE FUNCTION public.enforce_tenant_staff_seat_limit();

-- A staff-only or manager-only account cannot turn its business membership
-- into an owner account by calling the additional-business RPC directly.
CREATE OR REPLACE FUNCTION public.guard_staff_only_business_creation()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL OR COALESCE(auth.role() = 'service_role', FALSE) OR public.is_super_admin() THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.tenant_memberships membership
    WHERE membership.profile_id = auth.uid() AND membership.is_active = TRUE
  ) AND NOT EXISTS (
    SELECT 1
    FROM public.tenant_memberships membership
    JOIN public.roles role ON role.id = membership.role_id
    WHERE membership.profile_id = auth.uid()
      AND membership.is_active = TRUE
      AND UPPER(role.name) = 'OWNER'
  ) THEN
    RAISE EXCEPTION 'Staff and managers cannot create businesses from a team account.'
      USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.guard_staff_only_business_creation() FROM PUBLIC;
DROP TRIGGER IF EXISTS trg_guard_staff_only_business_creation ON public.tenants;
CREATE TRIGGER trg_guard_staff_only_business_creation
BEFORE INSERT ON public.tenants
FOR EACH ROW EXECUTE FUNCTION public.guard_staff_only_business_creation();

CREATE OR REPLACE FUNCTION public.guard_tenant_plan_staff_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_capacity INTEGER;
  v_active INTEGER;
  v_paid INTEGER;
BEGIN
  IF NEW.plan IS NOT DISTINCT FROM OLD.plan THEN RETURN NEW; END IF;
  SELECT COALESCE(paid_staff_seats, 0) INTO v_paid
  FROM public.tenant_seat_entitlements WHERE tenant_id = NEW.id;
  IF COALESCE(v_paid, 0) > (
    public.team_plan_max_staff(NEW.plan) - public.team_plan_included_staff(NEW.plan)
  ) THEN
    RAISE EXCEPTION 'Reduce paid staff seats before changing this business plan.'
      USING ERRCODE = 'P0001';
  END IF;
  v_capacity := LEAST(
    public.team_plan_max_staff(NEW.plan),
    public.team_plan_included_staff(NEW.plan) + COALESCE(v_paid, 0)
  );
  SELECT COUNT(*)::INTEGER INTO v_active
  FROM public.tenant_memberships membership
  JOIN public.roles role ON role.id = membership.role_id
  WHERE membership.tenant_id = NEW.id AND membership.is_active = TRUE
    AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF');
  IF v_active > v_capacity THEN
    RAISE EXCEPTION 'Deactivate staff or authorize enough seats before changing this business plan.'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.guard_tenant_plan_staff_capacity() FROM PUBLIC;
DROP TRIGGER IF EXISTS trg_guard_tenant_plan_staff_capacity ON public.tenants;
CREATE TRIGGER trg_guard_tenant_plan_staff_capacity
BEFORE UPDATE OF plan ON public.tenants
FOR EACH ROW EXECUTE FUNCTION public.guard_tenant_plan_staff_capacity();

CREATE OR REPLACE FUNCTION public.get_tenant_team_summary(p_tenant_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_plan TEXT;
  v_included INTEGER;
  v_max INTEGER;
  v_paid INTEGER;
  v_capacity INTEGER;
  v_active_staff INTEGER;
  v_result JSONB;
BEGIN
  IF NOT public.current_user_owns_tenant(p_tenant_id) THEN
    RAISE EXCEPTION 'Only the business owner can manage Team & Access.' USING ERRCODE = '42501';
  END IF;

  UPDATE public.team_invitations
  SET status = 'EXPIRED'
  WHERE tenant_id = p_tenant_id AND status = 'PENDING' AND expires_at <= NOW();

  SELECT CASE LOWER(COALESCE(tenant.plan::TEXT, 'starter'))
    WHEN 'pro' THEN 'pro'
    WHEN 'enterprise' THEN 'enterprise'
    ELSE 'starter'
  END INTO v_plan
  FROM public.tenants tenant WHERE tenant.id = p_tenant_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Business not found.' USING ERRCODE = 'P0002'; END IF;

  INSERT INTO public.tenant_seat_entitlements (tenant_id)
  VALUES (p_tenant_id) ON CONFLICT (tenant_id) DO NOTHING;

  SELECT paid_staff_seats INTO v_paid
  FROM public.tenant_seat_entitlements WHERE tenant_id = p_tenant_id;
  v_included := public.team_plan_included_staff(v_plan);
  v_max := public.team_plan_max_staff(v_plan);
  v_capacity := LEAST(v_max, v_included + COALESCE(v_paid, 0));

  SELECT COUNT(*)::INTEGER INTO v_active_staff
  FROM public.tenant_memberships membership
  JOIN public.roles role ON role.id = membership.role_id
  WHERE membership.tenant_id = p_tenant_id
    AND membership.is_active = TRUE
    AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF');

  SELECT JSONB_BUILD_OBJECT(
    'tenantId', p_tenant_id,
    'plan', v_plan,
    'includedStaff', v_included,
    'maxStaff', v_max,
    'paidStaffSeats', COALESCE(v_paid, 0),
    'authorizedStaff', v_capacity,
    'activeStaff', v_active_staff,
    'additionalSeatPrice', 2,
    'monthlySeatCharge', COALESCE(v_paid, 0) * 2,
    'members', COALESCE((
      SELECT JSONB_AGG(JSONB_BUILD_OBJECT(
        'membershipId', membership.id,
        'profileId', profile.id,
        'name', COALESCE(NULLIF(BTRIM(profile.full_name), ''), SPLIT_PART(profile.email, '@', 1)),
        'email', profile.email,
        'role', LOWER(role.name),
        'isActive', membership.is_active,
        'joinedAt', membership.joined_at
      ) ORDER BY CASE WHEN UPPER(role.name) = 'OWNER' THEN 0 ELSE 1 END, membership.joined_at)
      FROM public.tenant_memberships membership
      JOIN public.roles role ON role.id = membership.role_id
      JOIN public.profiles profile ON profile.id = membership.profile_id
      WHERE membership.tenant_id = p_tenant_id
    ), '[]'::JSONB),
    'invitations', COALESCE((
      SELECT JSONB_AGG(JSONB_BUILD_OBJECT(
        'id', invitation.id,
        'email', invitation.email,
        'role', LOWER(invitation.role_name),
        'status', LOWER(invitation.status),
        'expiresAt', invitation.expires_at,
        'createdAt', invitation.created_at
      ) ORDER BY invitation.created_at DESC)
      FROM public.team_invitations invitation
      WHERE invitation.tenant_id = p_tenant_id
        AND invitation.status = 'PENDING'
    ), '[]'::JSONB),
    'pendingSeatRequest', (
      SELECT JSONB_BUILD_OBJECT(
        'id', request.id,
        'requestedPaidSeats', request.requested_paid_seats,
        'status', LOWER(request.status),
        'createdAt', request.created_at
      )
      FROM public.tenant_seat_change_requests request
      WHERE request.tenant_id = p_tenant_id AND request.status = 'PENDING'
      ORDER BY request.created_at DESC LIMIT 1
    )
  ) INTO v_result;

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.get_tenant_team_summary(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_tenant_team_summary(UUID) TO authenticated;

CREATE OR REPLACE FUNCTION public.create_team_invitation(
  p_tenant_id UUID,
  p_email TEXT,
  p_role_name TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_email TEXT := LOWER(BTRIM(COALESCE(p_email, '')));
  v_role TEXT := UPPER(BTRIM(COALESCE(p_role_name, '')));
  v_token TEXT := REPLACE(gen_random_uuid()::TEXT, '-', '')
    || REPLACE(gen_random_uuid()::TEXT, '-', '');
  v_invitation public.team_invitations;
  v_capacity INTEGER;
  v_active INTEGER;
  v_pending INTEGER;
BEGIN
  IF NOT public.current_user_owns_tenant(p_tenant_id) THEN
    RAISE EXCEPTION 'Only the business owner can invite team members.' USING ERRCODE = '42501';
  END IF;
  IF NOT public.tenant_subscription_allows_access(p_tenant_id) THEN
    RAISE EXCEPTION 'This business subscription is inactive.' USING ERRCODE = '42501';
  END IF;
  IF v_role NOT IN ('MANAGER', 'STAFF') THEN
    RAISE EXCEPTION 'Choose Manager or Staff.' USING ERRCODE = '22023';
  END IF;
  IF LENGTH(v_email) < 5 OR POSITION('@' IN v_email) < 2 THEN
    RAISE EXCEPTION 'Enter a valid staff email address.' USING ERRCODE = '22023';
  END IF;

  PERFORM PG_ADVISORY_XACT_LOCK(HASHTEXT('team-seats:' || p_tenant_id::TEXT));
  v_capacity := COALESCE(public.tenant_authorized_staff_capacity(p_tenant_id), 0);

  IF EXISTS (
    SELECT 1 FROM public.tenant_memberships membership
    JOIN public.profiles profile ON profile.id = membership.profile_id
    WHERE membership.tenant_id = p_tenant_id
      AND membership.is_active = TRUE
      AND LOWER(profile.email) = v_email
  ) THEN
    RAISE EXCEPTION 'This email already has access to the business.' USING ERRCODE = '23505';
  END IF;

  UPDATE public.team_invitations
  SET status = CASE WHEN expires_at <= NOW() THEN 'EXPIRED' ELSE 'REVOKED' END,
      revoked_at = CASE WHEN expires_at > NOW() THEN NOW() ELSE revoked_at END
  WHERE tenant_id = p_tenant_id AND LOWER(email) = v_email AND status = 'PENDING';

  SELECT COUNT(*)::INTEGER INTO v_active
  FROM public.tenant_memberships membership
  JOIN public.roles role ON role.id = membership.role_id
  WHERE membership.tenant_id = p_tenant_id
    AND membership.is_active = TRUE
    AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF');

  SELECT COUNT(*)::INTEGER INTO v_pending
  FROM public.team_invitations invitation
  WHERE invitation.tenant_id = p_tenant_id
    AND invitation.status = 'PENDING'
    AND invitation.expires_at > NOW();

  IF v_active + v_pending >= v_capacity THEN
    RAISE EXCEPTION 'No authorized staff seat is available. Request a paid seat or change plans first.'
      USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.team_invitations (
    tenant_id, email, role_name, token_hash, invited_by
  ) VALUES (
    p_tenant_id,
    v_email,
    v_role,
    ENCODE(SHA256(CONVERT_TO(v_token, 'UTF8')), 'hex'),
    auth.uid()
  ) RETURNING * INTO v_invitation;

  INSERT INTO public.team_access_events (
    tenant_id, actor_id, action, invitation_id, details
  ) VALUES (
    p_tenant_id, auth.uid(), 'TEAM_INVITATION_CREATED', v_invitation.id,
    JSONB_BUILD_OBJECT('email', v_email, 'role', v_role, 'expiresAt', v_invitation.expires_at)
  );

  RETURN JSONB_BUILD_OBJECT(
    'id', v_invitation.id,
    'token', v_token,
    'email', v_email,
    'role', LOWER(v_role),
    'expiresAt', v_invitation.expires_at
  );
END;
$$;

REVOKE ALL ON FUNCTION public.create_team_invitation(UUID, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_team_invitation(UUID, TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.accept_team_invitation(
  p_token TEXT,
  p_full_name TEXT DEFAULT ''
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_auth_email TEXT;
  v_invitation public.team_invitations;
  v_role_id UUID;
  v_capacity INTEGER;
  v_active INTEGER;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Sign in with the invited email before accepting.' USING ERRCODE = '28000';
  END IF;

  SELECT LOWER(email) INTO v_auth_email FROM auth.users WHERE id = v_user_id;
  SELECT * INTO v_invitation
  FROM public.team_invitations invitation
  WHERE invitation.token_hash = ENCODE(
    SHA256(CONVERT_TO(COALESCE(p_token, ''), 'UTF8')),
    'hex'
  )
  FOR UPDATE;

  IF v_invitation.id IS NULL OR v_invitation.status <> 'PENDING' THEN
    RAISE EXCEPTION 'This invitation is invalid or has already been used.' USING ERRCODE = '22023';
  END IF;
  IF v_invitation.expires_at <= NOW() THEN
    UPDATE public.team_invitations SET status = 'EXPIRED' WHERE id = v_invitation.id;
    RAISE EXCEPTION 'This invitation has expired. Ask the owner for a new one.' USING ERRCODE = '22023';
  END IF;
  IF v_auth_email IS NULL OR v_auth_email <> LOWER(v_invitation.email) THEN
    RAISE EXCEPTION 'Sign in using the email address that received this invitation.' USING ERRCODE = '42501';
  END IF;
  IF NOT public.tenant_subscription_allows_access(v_invitation.tenant_id) THEN
    RAISE EXCEPTION 'This business subscription is inactive.' USING ERRCODE = '42501';
  END IF;

  PERFORM PG_ADVISORY_XACT_LOCK(HASHTEXT('team-seats:' || v_invitation.tenant_id::TEXT));
  v_capacity := COALESCE(public.tenant_authorized_staff_capacity(v_invitation.tenant_id), 0);

  SELECT COUNT(*)::INTEGER INTO v_active
  FROM public.tenant_memberships membership
  JOIN public.roles role ON role.id = membership.role_id
  WHERE membership.tenant_id = v_invitation.tenant_id
    AND membership.is_active = TRUE
    AND UPPER(role.name) IN ('ADMIN', 'MANAGER', 'STAFF')
    AND membership.profile_id <> v_user_id;

  IF v_active >= v_capacity THEN
    RAISE EXCEPTION 'This business no longer has an available staff seat.' USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (SELECT 1 FROM public.profiles WHERE id = v_user_id AND is_active = FALSE) THEN
    RAISE EXCEPTION 'This account has been deactivated.' USING ERRCODE = '42501';
  END IF;

  INSERT INTO public.profiles (id, full_name, email, is_active)
  VALUES (
    v_user_id,
    COALESCE(NULLIF(BTRIM(p_full_name), ''), SPLIT_PART(v_auth_email, '@', 1)),
    v_auth_email,
    TRUE
  )
  ON CONFLICT (id) DO UPDATE
  SET full_name = CASE
        WHEN NULLIF(BTRIM(p_full_name), '') IS NOT NULL THEN BTRIM(p_full_name)
        ELSE public.profiles.full_name
      END,
      email = EXCLUDED.email,
      updated_at = NOW();

  SELECT id INTO v_role_id FROM public.roles
  WHERE tenant_id = v_invitation.tenant_id
    AND UPPER(name) = v_invitation.role_name
  LIMIT 1;
  IF v_role_id IS NULL THEN
    INSERT INTO public.roles (tenant_id, name, description, is_system_role)
    VALUES (
      v_invitation.tenant_id,
      v_invitation.role_name,
      CASE WHEN v_invitation.role_name = 'MANAGER'
        THEN 'Business manager with daily operations access'
        ELSE 'Staff member with operational access'
      END,
      TRUE
    ) RETURNING id INTO v_role_id;
  END IF;

  INSERT INTO public.tenant_memberships (tenant_id, profile_id, role_id, is_active)
  VALUES (v_invitation.tenant_id, v_user_id, v_role_id, TRUE)
  ON CONFLICT ON CONSTRAINT tenant_memberships_tenant_id_profile_id_key DO UPDATE
  SET role_id = EXCLUDED.role_id, is_active = TRUE;

